function t(key, params = {}, langOverride = null) {
  const lang = normalizeLang(langOverride || currentLang);
  const dict = MESSAGES[lang] || MESSAGES.tr;
  let template = dict[key];
  if (template === undefined) template = MESSAGES.tr[key];
  if (template === undefined) return key;
  return String(template).replace(/\{(\w+)\}/g, (_m, k) =>
    params && Object.prototype.hasOwnProperty.call(params, k) && params[k] !== undefined && params[k] !== null
      ? String(params[k])
      : ''
  );
}

