const SUPPORTED_LANGS = ['tr', 'en', 'ru', 'de'];

const LANG_META = {
  tr: { code: 'tr', name: 'Türkçe', nativeName: 'Türkçe', locale: 'tr-TR' },
  en: { code: 'en', name: 'English', nativeName: 'English', locale: 'en-US' },
  ru: { code: 'ru', name: 'Русский', nativeName: 'Русский', locale: 'ru-RU' },
  de: { code: 'de', name: 'Deutsch', nativeName: 'Deutsch', locale: 'de-DE' }
};

let currentLang = 'tr';

function normalizeLang(lang) {
  const code = String(lang || '')
    .trim()
    .toLowerCase()
    .slice(0, 2);
  return SUPPORTED_LANGS.includes(code) ? code : 'tr';
}

function setLang(lang) {
  currentLang = normalizeLang(lang);
  return currentLang;
}

function getLang() {
  return currentLang;
}

function getLangMeta(lang) {
  return LANG_META[normalizeLang(lang || currentLang)];
}

